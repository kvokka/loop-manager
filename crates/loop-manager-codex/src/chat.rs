//! Visible messages and tool I/O in a thread's rollout. Read each from one representation only:
//! the user item omits injected environment messages, and response items include the model's original tool input.

use loop_manager_contract::driver::chat::ChatEntry;
use serde_json::Value;
use std::{
    io,
    path::{Path, PathBuf},
};

/// A closed thread no longer has the path from thread/start in memory. Its filename ends in its unique thread ID.
pub(super) fn saved(home: &Path, thread: &str) -> io::Result<PathBuf> {
    let suffix = format!("-{thread}.jsonl");
    for entry in walkdir::WalkDir::new(home.join("sessions")).max_depth(4) {
        let entry = entry?;
        if entry.file_type().is_file() && entry.file_name().to_string_lossy().ends_with(&suffix) {
            return Ok(entry.into_path());
        }
    }
    Err(io::Error::new(
        io::ErrorKind::NotFound,
        format!("no transcript for thread {thread}"),
    ))
}

/// `send_prompt` gives the `PromptKey` as `clientUserMessageId`; the rollout keeps it as the user item's `client_id`,
/// as `thread/read` (`transcript`) gives it as the `userMessage` item's `clientId`.
pub(super) fn prompt(record: &Value) -> Option<String> {
    user(record)?["client_id"].as_str().map(str::to_owned)
}

fn user(record: &Value) -> Option<&Value> {
    let payload = &record["payload"];
    (record["type"] == "event_msg" && payload["type"] == "item_completed" && payload["item"]["type"] == "UserMessage")
        .then(|| &payload["item"])
}

pub(super) fn entries(record: &Value) -> Vec<ChatEntry> {
    if let Some(item) = user(record) {
        return texts(item).map(|text| ChatEntry::User { text }).collect();
    }
    let payload = &record["payload"];
    if record["type"] != "response_item" {
        return Vec::new();
    }
    if payload["type"] == "message" && payload["role"] == "assistant" {
        return texts(payload).map(|text| ChatEntry::Assistant { text }).collect();
    }
    let id = payload["call_id"]
        .as_str()
        .or_else(|| payload["id"].as_str())
        .map(str::to_owned);
    let call = |name: &str, input: Value| ChatEntry::ToolCall {
        id: id.clone(),
        name: name.into(),
        input,
    };
    let result = |output: Value| ChatEntry::ToolResult {
        id: id.clone(),
        output,
        is_error: None,
    };
    match payload["type"].as_str() {
        Some("function_call" | "custom_tool_call") => {
            let Some(name) = payload["name"].as_str() else {
                return Vec::new();
            };
            let name = match payload["namespace"].as_str() {
                Some(namespace) => format!("{namespace}.{name}"),
                None => name.to_owned(),
            };
            let input = if let Some(args) = payload["arguments"].as_str() {
                serde_json::from_str(args).unwrap_or_else(|_| Value::String(args.into()))
            } else {
                payload["input"].clone()
            };
            vec![call(&name, input)]
        }
        Some("function_call_output" | "custom_tool_call_output") => vec![result(payload["output"].clone())],
        Some("tool_search_call") => vec![call("tool_search", payload["arguments"].clone())],
        Some("tool_search_output") => vec![result(payload["tools"].clone())],
        Some("local_shell_call") => vec![call("local_shell", payload["action"].clone())],
        Some("web_search_call") => vec![call("web_search", payload["action"].clone())],
        Some("image_generation_call") => {
            // The generated bytes are base64 in the rollout. The terminal shows the prompt and completion status.
            vec![
                call("image_generation", payload["revised_prompt"].clone()),
                result(payload["status"].clone()),
            ]
        }
        _ => Vec::new(),
    }
}

fn texts(item: &Value) -> impl Iterator<Item = String> {
    item["content"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(|b| b["text"].as_str().map(str::to_owned))
}
